  static List<WorldCity> get popularCities =>
      allCities.where((c) => c.isPopular).toList();

  /// Search cities by name, country, timezone ID, or keywords
  static List<WorldCity> search(String query) {
    final cleanQuery = query.trim().toLowerCase();
    if (cleanQuery.isEmpty) {
      return popularCities;
    }

    return allCities.where((city) {
      if (city.name.toLowerCase().contains(cleanQuery)) return true;
      if (city.country.toLowerCase().contains(cleanQuery)) return true;
      if (city.timezoneId.toLowerCase().contains(cleanQuery)) return true;
      if (city.countryCode.toLowerCase() == cleanQuery) return true;
      for (final kw in city.searchKeywords) {
        if (kw.toLowerCase().contains(cleanQuery)) return true;
      }
      return false;
    }).toList();
  }

  /// Find city by ID
  static WorldCity? findById(String id) {
    try {
      return allCities.firstWhere((c) => c.id == id);
    } catch (_) {
      return null;
    }
  }

  /// Find city closest to timezone ID
  static WorldCity? findByTimezone(String timezoneId) {
    try {
      return allCities.firstWhere((c) => c.timezoneId == timezoneId);
    } catch (_) {
      return null;
    }
  }
